using System.Net;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace HardeningChecker.Core;

public static class Reports
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
    };

    public static string ToJson(ScanReport r) => JsonSerializer.Serialize(new
    {
        tool = "Hardening Checker",
        version = typeof(Reports).Assembly.GetName().Version?.ToString(3),
        machine = r.MachineName,
        os = r.Os.Caption,
        build = r.Os.Build,
        elevated = r.IsElevated,
        startedAt = r.StartedAt,
        score = r.Score,
        results = r.Outcomes.Select(o => new
        {
            id = o.Check.Id,
            title = o.Check.Title,
            category = o.Check.Category,
            severity = o.Check.Severity,
            status = o.Result.Status,
            evidence = o.Result.Evidence,
            remediation = o.Check.Remediation,
            remediationCommand = o.Check.RemediationCommand,
        }),
    }, JsonOptions);

    public static string ToHtml(ScanReport r)
    {
        static string E(string? s) => WebUtility.HtmlEncode(s ?? "");
        var sb = new StringBuilder();
        sb.Append("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
        sb.Append($"<title>Hardening report: {E(r.MachineName)}</title><style>");
        sb.Append("body{font-family:Segoe UI,system-ui,sans-serif;margin:0;background:#f5f6f8;color:#1b1f24}");
        sb.Append(".wrap{max-width:1000px;margin:0 auto;padding:32px 20px}h1{margin:0 0 4px}.meta{color:#5b6470;margin:0 0 24px}");
        sb.Append(".score{display:flex;gap:16px;flex-wrap:wrap;margin-bottom:24px}.tile{background:#fff;border:1px solid #e1e4e8;border-radius:10px;padding:14px 18px;min-width:120px}");
        sb.Append(".tile b{display:block;font-size:26px}.chk{background:#fff;border:1px solid #e1e4e8;border-left:5px solid #9aa2ad;border-radius:8px;padding:14px 18px;margin:0 0 12px}");
        sb.Append(".Pass{border-left-color:#1f9d55}.Warning{border-left-color:#d9a400}.Fail{border-left-color:#d93025}.NeedsAdmin{border-left-color:#6b5bd2}");
        sb.Append(".st{font-weight:600;font-size:13px;text-transform:uppercase;letter-spacing:.4px}.chk h3{margin:4px 0 6px;font-size:17px}.ev{font-family:Consolas,monospace;font-size:13px;background:#f1f3f5;padding:6px 8px;border-radius:5px}");
        sb.Append("pre{background:#1b1f24;color:#e6edf3;padding:10px;border-radius:6px;overflow-x:auto;font-size:12.5px}.muted{color:#5b6470;font-size:14px}a{color:#0b62c4}</style></head><body><div class=\"wrap\">");
        sb.Append($"<h1>Hardening report</h1><p class=\"meta\">{E(r.MachineName)} · {E(r.Os.Caption)} (build {E(r.Os.Build)}) · {r.StartedAt:yyyy-MM-dd HH:mm} · {(r.IsElevated ? "run as administrator" : "run without administrator rights")}</p>");
        sb.Append("<div class=\"score\">");
        sb.Append($"<div class=\"tile\">Score<b>{r.Score} / 100</b></div>");
        foreach (var s in new[] { CheckStatus.Pass, CheckStatus.Warning, CheckStatus.Fail, CheckStatus.NeedsAdmin, CheckStatus.NotApplicable, CheckStatus.Error })
        {
            sb.Append($"<div class=\"tile\">{StatusLabel(s)}<b>{r.Count(s)}</b></div>");
        }
        sb.Append("</div>");
        foreach (var o in r.Outcomes.OrderBy(o => Rank(o.Result.Status)).ThenByDescending(o => o.Check.Severity))
        {
            var c = o.Check;
            sb.Append($"<div class=\"chk {o.Result.Status}\"><div class=\"st\">{StatusLabel(o.Result.Status)} · {c.Severity} · {c.Category} · {E(c.Id)}</div>");
            sb.Append($"<h3>{E(c.Title)}</h3><p class=\"ev\">{E(o.Result.Evidence)}</p>");
            if (o.Result.Status is CheckStatus.Fail or CheckStatus.Warning)
            {
                sb.Append($"<p><b>Why it matters:</b> {E(c.Rationale)}</p><p><b>How to fix:</b> {E(c.Remediation)}</p>");
                if (c.RemediationCommand is not null) sb.Append($"<pre>{E(c.RemediationCommand)}</pre>");
            }
            sb.Append("<p class=\"muted\">");
            sb.Append(string.Join(" · ", c.References.Select(rf => $"<a href=\"{E(rf.Url)}\">{E(rf.Label)}</a>")));
            sb.Append("</p></div>");
        }
        sb.Append("<p class=\"muted\">Generated by Hardening Checker (read-only scan, nothing was changed). https://github.com/JW-0042/win-hardening-checker</p></div></body></html>");
        return sb.ToString();
    }

    public static string StatusLabel(CheckStatus s) => s switch
    {
        CheckStatus.Pass => "Pass",
        CheckStatus.Warning => "Warning",
        CheckStatus.Fail => "Fail",
        CheckStatus.NeedsAdmin => "Needs admin",
        CheckStatus.NotApplicable => "Not applicable",
        _ => "Error",
    };

    public static int Rank(CheckStatus s) => s switch
    {
        CheckStatus.Fail => 0,
        CheckStatus.Warning => 1,
        CheckStatus.NeedsAdmin => 2,
        CheckStatus.Error => 3,
        CheckStatus.Pass => 4,
        _ => 5,
    };
}
